// Preserve shared subject, force, timing and connective text alongside every
// independently authored proof duty. This does not create an aggregate assertion
// or infer duties from sentence splitting; facets above determine acceptance.
func technicalSharedContext(statement string, facets []technicalFacet) []string {
	covered := make([]bool, len(statement))
	for _, f := range facets {
		start := strings.Index(statement, f.clause)
		if start < 0 {
			continue
		}
		for i := start; i < start+len(f.clause); i++ {
			covered[i] = true
		}
	}
	var context []string
	for i := 0; i < len(statement); {
		if covered[i] {
			i++
			continue
		}
		start := i
		for i < len(statement) && !covered[i] {
			i++
		}
		if text := strings.TrimSpace(statement[start:i]); text != "" {
			context = append(context, text)
		}
	}
	return context
}
