// technicalRecipe is authored outcome guidance, not a rule-to-checklist fallback.
// Each builder supplies every supported indicator explicitly. Inventory is used
// only to bind these recipes to exact profile/force variants.
type technicalRecipe struct {
	code, statement, purpose, capability, scope, setup, records, review, insufficient string
	timing                                                                            string
	facets                                                                            []technicalFacet
}

type technicalFacet struct{ clause, fact, records, insufficient string }

func technicalDraft(rules, markdown fs.FS, domain, page string, expected int, recipes []technicalRecipe) (readiness.Package, error) {
	raw, err := fs.ReadFile(rules, "rules.json")
	if err != nil {
		return readiness.Package{}, err
	}
	schema, err := fs.ReadFile(rules, "schema.json")
	if err != nil {
		return readiness.Package{}, err
	}
	snapshot, err := catalog.Parse(raw, schema, catalog.PinnedCommit)
	if err != nil {
		return readiness.Package{}, err
	}
	inventory, err := draftInventory(snapshot)
	if err != nil {
		return readiness.Package{}, err
	}
	p := readiness.Package{Format: readiness.Format, CatalogID: snapshot.ID, Revision: 1, Sources: map[string]readiness.Source{
		"rules": {Repository: "FedRAMP/rules", Commit: catalog.PinnedCommit},
		"site":  {Repository: "FedRAMP/2026", Commit: "8404168e6c150b40e4d0e45152d18965ab27e001"},
	}}
	add := func(id, source, path, anchor, excerpt string) error {
		root := markdown
		if source == "rules" {
			root = rules
		}
		c, e := citation(root, id, source, path, anchor, excerpt)
		if e == nil {
			p.Citations = append(p.Citations, c)
		}
		return e
	}
	for _, c := range []struct{ id, anchor, text string }{
		{"persistent", "persistently", persistentDefinition},
		{"regular", "regularly", "Performing the activity on a consistent, predictable, and repeated basis, at set intervals, automatically if possible, following a documented plan. These intervals may vary as appropriate between different activities."},
		{"prompt", "promptly", "Without unnecessary delay."},
		{"resources", "information-resource", "Has the meaning from 44 USC § 3502 (6): \"information and related resources, such as personnel, equipment, funds, and information technology.\" This includes any aspect of the cloud service offering, both technical and managerial, including everything that makes up the business of the offering from non-machine-based information resources like organizational policies, procedures, employees, etc. to machine-based information resources like hardware, software, cloud services, code, etc."},
		{"machine", "machine-based-information-resources", "Any information technology information resource—including systems, processes, software, hardware, services, cloud-native capabilities, and any other such capability, component, or resource—that relies primarily on mechanical or electronic devices (i.e. computers) for operation."},
		{"drift", "drift", "Changes to information resources that cause deviations from the intended and assessed state; common forms of drift include changes to configurations, deployed software, privileges, running processes, and availability."},
		{"validation", "validation", "Confirmation through objective evidence that implemented security capabilities and related certification data are suitable for their intended FedRAMP Certification use and support the expected security outcomes for a cloud service offering."},
		{"likely", "likely", "A reasonable degree of probability based on context."},
		{"vulnerability", "vulnerability", "This includes gaps in Rev5 Controls and 20x Key Security Indicators, software vulnerabilities, misconfigurations, exposures, weak credentials, insecure services, and all other such potential weaknesses in protection (intentional or unintentional)."},
		{"customer-data", "federal-customer-data", "All electronic information, content, and materials that an agency or its authorized users upload, store, or otherwise supply to a cloud service for processing or storage. This does NOT include account information, service metadata, analytics, telemetry, or other similar metadata generated by the cloud service provider."},
		{"response", "vulnerability-response", "The systematic process of tracking, evaluating, mitigating, monitoring, remediating, assessing exploitation, reporting, and otherwise managing detected vulnerabilities."},
		{"offering", "cloud-service-offering", "A specific, packaged cloud computing product or service supplied by a cloud service provider for use by customers, that is the subject of a FedRAMP Certification."},
	} {
		if err = add(c.id, "site", "definitions.md", c.anchor, c.text); err != nil {
			return p, err
		}
	}
	if err = add("outcomes", "site", "providers/20x/key-security-indicators/index.md", "getting-started", "We are intentionally vague about the actual activities expected for each Key Security\nIndicator because these vary considerably by cloud service offering depending on many diverse factors."); err != nil {
		return p, err
	}
	if err = add("class-a", "site", "providers/20x/rules/fedramp-certification.md", "mandatory-fedramp-rules-for-class-a", "Providers seeking a Class A FedRAMP Certification [MUST](../../../definitions/#must){ data-preview } address all rules in this FedRAMP Class A Certification subset (FRC-CLA) AND the following additional FedRAMP Class A rules; the appropriate artifacts or information mapping for all rules [MUST](../../../definitions/#must){ data-preview } be supplied in the FedRAMP Certification Package."); err != nil {
		return p, err
	}
	byID := map[string]technicalRecipe{}
	caps := map[string]bool{}
	for _, r := range recipes {
		id := "KSI-" + domain + "-" + r.code
		if _, ok := byID[id]; ok {
			return p, fmt.Errorf("duplicate authored recipe %s", id)
		}
		byID[id] = r
		if err = add(id, "rules", "rules.json", "/KSI/"+domain+"/indicators/"+id, r.statement); err != nil {
			return p, err
		}
		pagePath := "providers/20x/key-security-indicators/" + page + ".md"
		pageRaw, e := fs.ReadFile(markdown, pagePath)
		if e != nil {
			return p, e
		}
		heading := ""
		for _, line := range strings.Split(string(pageRaw), "\n") {
			if strings.HasPrefix(line, "### ") {
				heading = strings.TrimPrefix(line, "### ")
			}
			if strings.Contains(line, `"`+id+`"`) {
				break
			}
		}
		anchor := strings.ToLower(strings.ReplaceAll(strings.ReplaceAll(heading, ",", ""), " ", "-"))
		if heading == "" {
			return p, fmt.Errorf("missing heading for %s", id)
		}
		if err = add(id+"-page", "site", pagePath, anchor, r.statement); err != nil {
			return p, err
		}
	}
	count := 0
	variantIDs := []string{}
	for _, v := range inventory.Variants {
		if !strings.HasPrefix(v.RequirementID, "KSI-"+domain+"-") {
			continue
		}
		count++
		variantIDs = append(variantIDs, v.ID)
		r, ok := byID[v.RequirementID]
		if !ok {
			return p, fmt.Errorf("unauthored indicator %s", v.RequirementID)
		}
		ref := v.RequirementID
		rec := func(text, why string) readiness.Statement {
			return readiness.Statement{Text: text, Basis: readiness.Recommendation, Rationale: why, Citations: append([]string{ref, ref + "-page", "outcomes"}, technicalTerms(ref)...)}
		}
		step := func(id, action, completion string) readiness.Step {
			return readiness.Step{ID: id, OwnerRole: domain + " evidence owner with responsible engineers or business owners", Trigger: "one_time", Action: rec(action, "Inspect existing operation and retain evidence for this outcome; this is not authorization to change the service."), CompletionCriteria: []readiness.Statement{rec(completion, "An attributable result and identified denominator allow a reviewer to assess this specific outcome.")}}
		}
		app := "Catalog applicability: " + v.Applicability + ". " + v.Reason + ". Preserve the saved certification path, class, date and service context."
		if v.IncludedBy != "" {
			app += " Included by " + v.IncludedBy + "."
		}
		b := readiness.Playbook{ID: strings.ToLower(ref) + "-" + v.ID[:12], Revision: 1, RequirementID: ref, VariantIDs: []string{v.ID}, OfficialStatement: v.Statement, Purpose: rec(r.purpose, "This distinguishes the indicator's outcome from evidence of tool purchase or policy intent."), Applicability: rec(app, "The exact inventory identity preserves class inclusion, exclusion, optional force and unresolved path/class decisions.")}
		b.Applicability.Citations = append(b.Applicability.Citations, "class-a")
		switch v.Applicability {
		case "not_applicable":
			b.Kind = "excluded"
			b.Applicability.Text += " This excludes only this profile's obligation; it makes no implementation or compliance finding."
		case "unresolved":
			b.Kind = "needs_decision"
			b.DecisionOwnerRole = "Service certification owner"
			b.DecisionQuestion = "Which authoritative KSI applicability applies to this saved certification path and class? Record the resolution and its source before evaluating implementation. Resolver reason: " + v.Reason
		case "required", "optional":
			if strings.TrimPrefix(v.Statement, "**Optional:** ") != r.statement {
				return p, fmt.Errorf("%s statement changed; reauthor guidance", ref)
			}
			b.Kind = "actionable"
			if v.Applicability == "optional" {
				b.Applicability.Text += " This exact Class B outcome is optional. The source and provider page supply B and C statements only; Class D has a separate unresolved variant, not inherited optionality. Use the evidence workflow only if the service elects to demonstrate it; do not turn it into a mandatory certification condition."
				if err = add(ref+"-optional", "rules", "rules.json", "/KSI/"+domain+"/indicators/"+ref+"/varies_by_class/b/statement", v.Statement); err != nil {
					return p, err
				}
				b.Applicability.Citations = append(b.Applicability.Citations, ref+"-optional")
			}
			if !caps[r.capability] {
				caps[r.capability] = true
				shared := step("locate-evidence-boundary", technicalCapabilitySetup(r.capability), "Record owners, read-only evidence locations, versions and boundary mappings. Reuse organizational records only with explicit coverage of this service and its accounts, clusters, namespaces or repositories.")
				shared.Action.Citations = []string{"outcomes"}
				shared.CompletionCriteria[0].Citations = []string{"outcomes"}
				p.Capabilities = append(p.Capabilities, readiness.Capability{ID: r.capability, Name: r.capability, ScopeKind: "service", Setup: readiness.Steps{Items: []readiness.Step{shared}}})
			}
			b.Prerequisites = []readiness.Dependency{{CapabilityID: r.capability, Reason: rec("An identified evidence boundary is needed for: "+r.scope, "This is an evidence prerequisite, not a separate required product, integration or remediation task.")}}
			b.Setup = readiness.Steps{Items: []readiness.Step{step("identify-outcome-records", r.setup, "Identify the records for "+r.scope+"; record unavailable sources as unknown implementation, not a failed security control.")}}
			b.Setup.Items = append(b.Setup.Items, step("establish-outcome-prerequisites", "Establish with the responsible owners whether the following substantive prerequisites exist: "+technicalPrerequisite[ref]+" If absent, record the design or implementation work needed before this outcome can be demonstrated.", "Document the prerequisite state and responsible owners, separately from connector access and evidence collection readiness."))
			time := r.timing
			if time == "" {
				time = "Retain the actual observation and operating period. This indicator supplies no numeric deadline; a point-in-time record cannot establish historical operation."
			}
			if strings.Contains(strings.ToLower(r.statement), "persistent") {
				time += " Demonstrate repeated activity, known current status and intentional, understood, documented interruptions; no fixed monthly or annual interval is inferred from persistently."
			}
			timing := rec(time, "Preserve source timing and distinguish a documented service cadence from an official deadline.")
			op := step("observe-existing-operation", r.review, r.records)
			op.Trigger = "recurring"
			op.Timing = &timing
			if strings.Contains(r.timing, "When ") {
				op.Trigger = "event"
			}
			b.Operate = readiness.Steps{Items: []readiness.Step{op}}
			b.Collect = readiness.Steps{Items: []readiness.Step{step("collect-outcome-evidence", "Collect retained revisions of: "+r.records, "Record collection identity, source system, resource or business population, artifact revision and timestamps. Keep access failures distinct from missing operating evidence.")}}
			b.ReviewSteps = readiness.Steps{Items: []readiness.Step{step("evaluate-outcome", r.review, "Assess every assertion against cited artifact revisions and its population and period. Explain sampling, exceptions and contradictory evidence. Missing evidence means unknown implementation; a collection success is not a sufficiency finding.")}}
			facets := technicalReviewedFacets(ref, r)
			context := technicalSharedContext(v.Statement, facets)
			for n, a := range facets {
				ac := readiness.Acceptance{Fact: a.fact, Scope: rec(r.scope, "The population named by the outcome, not a convenient connector subset, is the evidence denominator."), TimePeriod: timing, Provenance: rec("Retain source identifiers and versions for "+a.records+" Attribute observations to the collector, review method, responsible owner and dates; link conclusions to exact artifact revisions.", "Provenance must connect the claimed outcome to the actual population and period examined."), Insufficient: []string{a.insufficient, "Unsupported declaration, missing evidence interpreted as implementation failure, or collection status treated as assurance."}}
				ac.Alternatives = []readiness.EvidenceRoute{
					{ID: "source-exports", Artifacts: []readiness.Statement{rec(a.records, "Collect these outcome-specific records from their authoritative systems with read-only access; exports do not themselves certify sufficiency.")}, Proves: a.fact, Limitations: "Limited to the exported population, period and fields. Insufficient for this assertion: " + a.insufficient},
					{ID: "attributable-records", Artifacts: []readiness.Statement{rec("Use retained reports or a witnessed, read-only examination documenting the same facts: "+a.records, "An attributable examination can substitute for direct integration, but cannot substitute manual operation where automation is part of the indicator.")}, Proves: a.fact, Limitations: "The examiner must identify original sources, exact revisions, observation dates and coverage. Interviews or screenshots without this chain cannot establish the full outcome; preserve automation evidence where required."},
				}
				refs := []string{ref, ref + "-page"}
				if v.Applicability == "optional" {
					refs = append(refs, ref+"-optional")
				}
				b.Assertions = append(b.Assertions, readiness.Assertion{ID: fmt.Sprintf("outcome-%d", n+1), Clauses: append([]string{a.clause}, context...), Obligation: readiness.Statement{Text: a.clause, Basis: readiness.Official, Citations: refs}, Acceptance: ac})
			}
		default:
			return p, fmt.Errorf("unreviewed applicability %s", v.Applicability)
		}
		p.Playbooks = append(p.Playbooks, b)
	}
	if count != expected {
		return p, fmt.Errorf("%s inventory changed: got %d want %d", domain, count, expected)
	}
	sort.Strings(variantIDs)
	if storage.Hash([]byte(strings.Join(variantIDs, "\n")+"\n")) != technicalVariantDigest[domain] {
		return p, fmt.Errorf("%s exact variant identities changed; reauthor against the new inventory", domain)
	}
	if err = readiness.ValidateDraft(p); err != nil {
		return p, err
	}
	return p, readiness.VerifySources(p, rules, markdown)
}

